#!/bin/sh
# Generate .env.lakehouse with random local secrets. Existing values are never changed;
# keys missing from an older file (e.g. Airflow's) are appended.
set -eu
f=.env.lakehouse
rand() { python3 -c 'import secrets; print(secrets.token_urlsafe(24))'; }
hex() { python3 -c "import secrets; print(secrets.token_hex($1))"; }
umask 077
[ -f "$f" ] || echo "# Lakehouse secrets. Generated by scripts/make-lakehouse-env.sh. Git-ignored." > "$f"
add() { grep -q "^$1=" "$f" || echo "$1=$2" >> "$f"; }
add LAKEHOUSE_CATALOG_PASSWORD "$(rand)"
# Garage formats: key id GK + 24 hex, secret and RPC secret 64 hex.
add LAKEHOUSE_S3_ACCESS_KEY "GK$(hex 12)"
add LAKEHOUSE_S3_SECRET_KEY "$(hex 32)"
add GARAGE_RPC_SECRET "$(hex 32)"
add GARAGE_ADMIN_TOKEN "$(rand)"
add AIRFLOW_DB_PASSWORD "$(rand)"
add AIRFLOW_ADMIN_PASSWORD "$(rand)"
add AIRFLOW_JWT_SECRET "$(hex 32)"
add AIRFLOW_FERNET_KEY "$(python3 -c 'import base64, os; print(base64.urlsafe_b64encode(os.urandom(32)).decode())')"
echo "$f is complete (mode 600)"
